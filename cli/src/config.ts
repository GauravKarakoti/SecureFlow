import fs from "node:fs";
import path from "node:path";
import readline from "node:readline";
import { compileIgnorePatterns, normalizeScanPath } from "./ignore.js";

export const CONFIG_FILE_NAME = ".secureflow.json";
export const FALLBACK_CONFIG_FILE_NAME = "secureflow.config.json";

export interface SecureFlowConfig {
  paths?: string[];
  severity?: string;
  aiRemediation?: boolean;
}

export interface PromptConfigOptions {
  stdin?: NodeJS.ReadableStream;
  stdout?: NodeJS.WritableStream;
  rl?: readline.Interface;
}

export interface InitConfigOptions extends PromptConfigOptions {
  cwd?: string;
  yes?: boolean;
  force?: boolean;
}

export interface InitConfigResult {
  success: boolean;
  message: string;
  configPath: string;
  created: boolean;
}

/**
 * Strip single-line (//) and multi-line (/* *\/) comments from JSON string
 * without altering strings or escape sequences.
 */
export function stripJsonComments(json: string): string {
  let insideString = false;
  let stringChar = "";
  let isEscaped = false;
  let result = "";

  for (let i = 0; i < json.length; i++) {
    const char = json[i];
    const nextChar = json[i + 1];

    if (insideString) {
      result += char;
      if (isEscaped) {
        isEscaped = false;
      } else if (char === "\\") {
        isEscaped = true;
      } else if (char === stringChar) {
        insideString = false;
      }
    } else {
      if (char === '"' || char === "'") {
        insideString = true;
        stringChar = char;
        result += char;
      } else if (char === "/" && nextChar === "/") {
        const newlineIndex = json.indexOf("\n", i);
        if (newlineIndex === -1) {
          break;
        }
        i = newlineIndex - 1;
      } else if (char === "/" && nextChar === "*") {
        const closeIndex = json.indexOf("*/", i + 2);
        if (closeIndex === -1) {
          break;
        }
        i = closeIndex + 1;
      } else {
        result += char;
      }
    }
  }

  return result;
}

/**
 * Generate human-readable commented JSON configuration file content.
 */
export function generateConfigFileContent(options: {
  paths: string[];
  severity: string;
  aiRemediation: boolean;
}): string {
  const formattedPaths = JSON.stringify(options.paths, null, 4)
    .split("\n")
    .map((line, idx) => (idx === 0 ? line : `  ${line}`))
    .join("\n");

  return `{
  // SecureFlow Configuration
  // Generated by \`secureflow init\`
  // Documentation: https://github.com/GauravKarakoti/SecureFlow

  // Paths to include in security scans (glob patterns or directory paths)
  "paths": ${formattedPaths},

  // Minimum severity threshold that triggers a failure (critical, high, medium, low)
  "severity": ${JSON.stringify(options.severity)},

  // Enable or disable AI-assisted security explanations and remediation suggestions
  "aiRemediation": ${options.aiRemediation}
}
`;
}

/**
 * Parse raw configuration text into structured SecureFlowConfig.
 */
export function parseConfigFile(content: string): SecureFlowConfig {
  const stripped = stripJsonComments(content);
  const parsed = JSON.parse(stripped);

  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error("Configuration root must be an object");
  }

  const result: SecureFlowConfig = {};

  if (parsed.paths !== undefined) {
    if (Array.isArray(parsed.paths)) {
      result.paths = parsed.paths.filter((p: unknown): p is string => typeof p === "string");
    } else if (typeof parsed.paths === "string") {
      result.paths = [parsed.paths];
    }
  }

  if (typeof parsed.severity === "string" && parsed.severity.trim()) {
    result.severity = parsed.severity.trim().toLowerCase();
  }

  if (typeof parsed.aiRemediation === "boolean") {
    result.aiRemediation = parsed.aiRemediation;
  }

  return result;
}

/**
 * Search and load configuration file (.secureflow.json or secureflow.config.json).
 */
export function loadConfigFile(targetDir: string = process.cwd()): {
  config: SecureFlowConfig;
  configPath: string;
} | null {
  const candidates = [
    path.resolve(targetDir, CONFIG_FILE_NAME),
    path.resolve(targetDir, FALLBACK_CONFIG_FILE_NAME),
  ];

  for (const candidate of candidates) {
    if (fs.existsSync(candidate)) {
      try {
        const raw = fs.readFileSync(candidate, "utf-8");
        const config = parseConfigFile(raw);
        return { config, configPath: candidate };
      } catch (err) {
        console.warn(
          `⚠️  [SecureFlow] Failed to parse configuration file at "${candidate}": ${
            err instanceof Error ? err.message : String(err)
          }. Falling back to default settings.`,
        );
        return null;
      }
    }
  }

  return null;
}

/**
 * Compiles scan path patterns (expanding simple directories like "src" to "src/**").
 */
export function compilePathPatterns(patterns: string[]): RegExp[] {
  const expanded: string[] = [];
  for (const p of patterns) {
    const trimmed = p.trim();
    if (!trimmed) continue;
    expanded.push(trimmed);
    if (!trimmed.includes("*") && !trimmed.endsWith("/")) {
      expanded.push(`${trimmed}/**`);
    }
  }
  return compileIgnorePatterns(expanded);
}

export class LineReader {
  private output: NodeJS.WritableStream | undefined;
  private rl: readline.Interface;
  private buffer: string[] = [];
  private waiters: Array<(line: string) => void> = [];
  private closed = false;

  constructor(input: NodeJS.ReadableStream, output?: NodeJS.WritableStream) {
    this.output = output;
    this.rl = readline.createInterface({
      input,
      terminal: false,
    });

    this.rl.on("line", (line: string) => {
      if (this.waiters.length > 0) {
        const resolve = this.waiters.shift()!;
        resolve(line);
      } else {
        this.buffer.push(line);
      }
    });

    this.rl.on("close", () => {
      this.closed = true;
      while (this.waiters.length > 0) {
        const resolve = this.waiters.shift()!;
        resolve("");
      }
    });
  }

  async ask(question: string): Promise<string> {
    if (this.output && (this.output as any).write) {
      this.output.write(question);
    }
    if (this.buffer.length > 0) {
      return this.buffer.shift()!.trim();
    }
    if (this.closed) {
      return "";
    }
    return new Promise((resolve) => {
      this.waiters.push((line) => resolve(line.trim()));
    });
  }

  close(): void {
    this.rl.close();
  }
}

/**
 * Prompts user interactively for scan paths, minimum severity, and AI remediation.
 */
export async function promptConfigValues(
  options: PromptConfigOptions = {},
): Promise<{ paths: string[]; severity: string; aiRemediation: boolean }> {
  let ask: (q: string) => Promise<string>;
  let cleanup: () => void;

  if (options.rl) {
    ask = (q: string) =>
      new Promise((resolve) => {
        options.rl!.question(q, (ans) => resolve(ans.trim()));
      });
    cleanup = () => {};
  } else {
    const reader = new LineReader(options.stdin || process.stdin, options.stdout || process.stdout);
    ask = (q: string) => reader.ask(q);
    cleanup = () => reader.close();
  }

  try {
    // 1. Scan paths
    const pathsAnswer = await ask(
      "Scan paths to include (comma-separated globs or directories) [src/**]: ",
    );
    let paths = ["src/**"];
    if (pathsAnswer) {
      const split = pathsAnswer
        .split(",")
        .map((p) => p.trim())
        .filter((p) => p.length > 0);
      if (split.length > 0) {
        paths = split;
      }
    }

    // 2. Minimum severity
    const severityAnswer = await ask(
      "Minimum severity threshold (low, medium, high, critical) [high]: ",
    );
    let severity = "high";
    if (severityAnswer) {
      const normalized = severityAnswer.toLowerCase();
      if (["low", "medium", "high", "critical"].includes(normalized)) {
        severity = normalized;
      }
    }

    // 3. AI remediation
    const aiAnswer = await ask("Enable AI remediation and explanations? (y/n) [y]: ");
    let aiRemediation = true;
    if (aiAnswer) {
      const lower = aiAnswer.toLowerCase();
      if (lower === "n" || lower === "no" || lower === "false" || lower === "0") {
        aiRemediation = false;
      }
    }

    return { paths, severity, aiRemediation };
  } finally {
    cleanup();
  }
}

/**
 * Initialize a SecureFlow configuration file in the target directory.
 */
export async function initConfigFile(options: InitConfigOptions = {}): Promise<InitConfigResult> {
  const cwd = options.cwd || process.cwd();
  const configPath = path.resolve(cwd, CONFIG_FILE_NAME);
  const exists = fs.existsSync(configPath);

  if (exists && !options.force) {
    return {
      success: false,
      message: `Configuration file already exists at ${CONFIG_FILE_NAME}. Use --force to overwrite.`,
      configPath,
      created: false,
    };
  }

  let values: { paths: string[]; severity: string; aiRemediation: boolean };

  if (options.yes) {
    values = {
      paths: ["src/**"],
      severity: "high",
      aiRemediation: true,
    };
  } else {
    values = await promptConfigValues(options);
  }

  const content = generateConfigFileContent(values);
  fs.writeFileSync(configPath, content, "utf-8");

  const message = exists
    ? `Overwrote existing configuration file at ${CONFIG_FILE_NAME}`
    : `Created configuration file at ${CONFIG_FILE_NAME}`;

  return {
    success: true,
    message,
    configPath,
    created: true,
  };
}
