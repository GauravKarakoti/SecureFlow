import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import {
  stripJsonComments,
  parseConfigFile,
  generateConfigFileContent,
  loadConfigFile,
  compilePathPatterns,
  promptConfigValues,
  initConfigFile,
  CONFIG_FILE_NAME,
  FALLBACK_CONFIG_FILE_NAME,
} from "./config.js";

describe("stripJsonComments", () => {
  it("removes single line comments", () => {
    const input = `{\n  // A comment\n  "key": "value" // Inline comment\n}`;
    const output = stripJsonComments(input);
    expect(JSON.parse(output)).toEqual({ key: "value" });
  });

  it("removes multi-line comments", () => {
    const input = `{\n  /* Multi-line\n     comment */\n  "key": "value"\n}`;
    const output = stripJsonComments(input);
    expect(JSON.parse(output)).toEqual({ key: "value" });
  });

  it("preserves slashes inside strings", () => {
    const input = `{\n  "url": "https://example.com/api",\n  "glob": "src/**/*.ts"\n}`;
    const output = stripJsonComments(input);
    expect(JSON.parse(output)).toEqual({
      url: "https://example.com/api",
      glob: "src/**/*.ts",
    });
  });

  it("handles escaped quotes inside strings", () => {
    const input = `{\n  "text": "Hello \\"world\\" // not a comment"\n}`;
    const output = stripJsonComments(input);
    expect(JSON.parse(output)).toEqual({
      text: 'Hello "world" // not a comment',
    });
  });
});

describe("parseConfigFile", () => {
  it("parses valid JSON with comments into SecureFlowConfig", () => {
    const content = `{
      // Configuration comment
      "paths": ["src/**", "lib/**"],
      "severity": "HIGH",
      "aiRemediation": false
    }`;

    const config = parseConfigFile(content);
    expect(config).toEqual({
      paths: ["src/**", "lib/**"],
      severity: "high",
      aiRemediation: false,
    });
  });

  it("converts single string path to array", () => {
    const content = `{\n  "paths": "src/**"\n}`;
    const config = parseConfigFile(content);
    expect(config.paths).toEqual(["src/**"]);
  });

  it("throws when root is not an object", () => {
    expect(() => parseConfigFile("[]")).toThrow("Configuration root must be an object");
    expect(() => parseConfigFile('"string"')).toThrow("Configuration root must be an object");
  });

  it("throws when JSON is invalid", () => {
    expect(() => parseConfigFile("{ broken json")).toThrow();
  });
});

describe("generateConfigFileContent", () => {
  it("generates commented content that can be round-trip parsed", () => {
    const content = generateConfigFileContent({
      paths: ["src/**", "packages/**"],
      severity: "medium",
      aiRemediation: true,
    });

    expect(content).toContain("// SecureFlow Configuration");
    expect(content).toContain("// Generated by `secureflow init`");
    expect(content).toContain('"paths": [\n');
    expect(content).toContain('"severity": "medium"');
    expect(content).toContain('"aiRemediation": true');

    const parsed = parseConfigFile(content);
    expect(parsed).toEqual({
      paths: ["src/**", "packages/**"],
      severity: "medium",
      aiRemediation: true,
    });
  });
});

describe("compilePathPatterns", () => {
  it("expands simple directory names to directory/**", () => {
    const patterns = compilePathPatterns(["src", "lib/**", "*.ts"]);
    expect(patterns.some((re) => re.test("src/app.ts"))).toBe(true);
    expect(patterns.some((re) => re.test("lib/utils.ts"))).toBe(true);
    expect(patterns.some((re) => re.test("root.ts"))).toBe(true);
    expect(patterns.some((re) => re.test("docs/guide.md"))).toBe(false);
  });
});

describe("loadConfigFile", () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-config-test-"));
  });

  afterEach(() => {
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it("loads .secureflow.json when present", () => {
    const configPath = path.join(tempDir, CONFIG_FILE_NAME);
    fs.writeFileSync(
      configPath,
      generateConfigFileContent({
        paths: ["src/**"],
        severity: "critical",
        aiRemediation: false,
      }),
    );

    const result = loadConfigFile(tempDir);
    expect(result).not.toBeNull();
    expect(result?.config).toEqual({
      paths: ["src/**"],
      severity: "critical",
      aiRemediation: false,
    });
    expect(result?.configPath).toBe(configPath);
  });

  it("falls back to secureflow.config.json when .secureflow.json is absent", () => {
    const configPath = path.join(tempDir, FALLBACK_CONFIG_FILE_NAME);
    fs.writeFileSync(
      configPath,
      JSON.stringify({ paths: ["lib/**"], severity: "low", aiRemediation: true }),
    );

    const result = loadConfigFile(tempDir);
    expect(result).not.toBeNull();
    expect(result?.config).toEqual({
      paths: ["lib/**"],
      severity: "low",
      aiRemediation: true,
    });
  });

  it("returns null when no configuration file exists", () => {
    const result = loadConfigFile(tempDir);
    expect(result).toBeNull();
  });

  it("warns and returns null when configuration file is malformed", () => {
    const warnSpy = vi.spyOn(console, "warn").mockImplementation(() => {});
    const configPath = path.join(tempDir, CONFIG_FILE_NAME);
    fs.writeFileSync(configPath, "{ malformed json");

    const result = loadConfigFile(tempDir);
    expect(result).toBeNull();
    expect(warnSpy).toHaveBeenCalledWith(
      expect.stringContaining("Failed to parse configuration file"),
    );

    warnSpy.mockRestore();
  });
});

describe("promptConfigValues", () => {
  it("resolves to user answered values", async () => {
    const answers = ["src/**, test/**", "critical", "n"];
    let callIndex = 0;
    const mockRl = {
      question: vi.fn((_q: string, cb: (ans: string) => void) => {
        cb(answers[callIndex++] || "");
      }),
      close: vi.fn(),
    } as any;

    const values = await promptConfigValues({ rl: mockRl });
    expect(values).toEqual({
      paths: ["src/**", "test/**"],
      severity: "critical",
      aiRemediation: false,
    });
  });

  it("falls back to defaults when user provides empty input", async () => {
    const mockRl = {
      question: vi.fn((_q: string, cb: (ans: string) => void) => {
        cb("");
      }),
      close: vi.fn(),
    } as any;

    const values = await promptConfigValues({ rl: mockRl });
    expect(values).toEqual({
      paths: ["src/**"],
      severity: "high",
      aiRemediation: true,
    });
  });
});

describe("initConfigFile", () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-test-"));
  });

  afterEach(() => {
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  it("creates .secureflow.json with defaults in --yes mode", async () => {
    const result = await initConfigFile({ cwd: tempDir, yes: true });
    expect(result.success).toBe(true);
    expect(result.created).toBe(true);
    expect(result.message).toContain("Created configuration file at .secureflow.json");

    const filePath = path.join(tempDir, CONFIG_FILE_NAME);
    expect(fs.existsSync(filePath)).toBe(true);

    const loaded = loadConfigFile(tempDir);
    expect(loaded?.config).toEqual({
      paths: ["src/**"],
      severity: "high",
      aiRemediation: true,
    });
  });

  it("refuses to overwrite an existing configuration file without --force", async () => {
    const filePath = path.join(tempDir, CONFIG_FILE_NAME);
    fs.writeFileSync(filePath, '{"original": true}');

    const result = await initConfigFile({ cwd: tempDir, yes: true, force: false });
    expect(result.success).toBe(false);
    expect(result.created).toBe(false);
    expect(result.message).toContain(
      "Configuration file already exists at .secureflow.json. Use --force to overwrite.",
    );

    // Verify existing content was not overwritten
    expect(fs.readFileSync(filePath, "utf-8")).toBe('{"original": true}');
  });

  it("overwrites an existing configuration file when --force is passed", async () => {
    const filePath = path.join(tempDir, CONFIG_FILE_NAME);
    fs.writeFileSync(filePath, '{"original": true}');

    const result = await initConfigFile({ cwd: tempDir, yes: true, force: true });
    expect(result.success).toBe(true);
    expect(result.created).toBe(true);
    expect(result.message).toContain("Overwrote existing configuration file at .secureflow.json");

    const loaded = loadConfigFile(tempDir);
    expect(loaded?.config).toEqual({
      paths: ["src/**"],
      severity: "high",
      aiRemediation: true,
    });
  });

  it("prompts interactively and writes custom configuration", async () => {
    const answers = ["custom-dir/**", "low", "false"];
    let callIndex = 0;
    const mockRl = {
      question: vi.fn((_q: string, cb: (ans: string) => void) => {
        cb(answers[callIndex++] || "");
      }),
      close: vi.fn(),
    } as any;

    const result = await initConfigFile({ cwd: tempDir, rl: mockRl });
    expect(result.success).toBe(true);

    const loaded = loadConfigFile(tempDir);
    expect(loaded?.config).toEqual({
      paths: ["custom-dir/**"],
      severity: "low",
      aiRemediation: false,
    });
  });
});
