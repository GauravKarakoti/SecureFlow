import { describe, it, expect, beforeAll, afterEach } from "vitest";
import { execSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const CLI_DIR = path.resolve(__dirname, "..");
const BIN_PATH = path.resolve(CLI_DIR, "dist/index.js");

interface RunResult {
  status: number | null;
  stdout: string;
  stderr: string;
}

function runCli(
  args: string[],
  cwd: string,
  input?: string,
  env: Record<string, string | undefined> = {},
): RunResult {
  const result = spawnSync("node", [BIN_PATH, ...args], {
    cwd,
    input: input !== undefined ? input : undefined,
    encoding: "utf-8",
    env: {
      ...process.env,
      NO_COLOR: "1",
      CI: "true",
      LOCAL_AI_URL: "http://127.0.0.1:0", // Prevent accidental external calls
      ...env,
    },
    timeout: 30000,
  });

  return {
    status: result.status,
    stdout: result.stdout || "",
    stderr: result.stderr || "",
  };
}

function initGitRepo(repoDir: string): void {
  fs.mkdirSync(repoDir, { recursive: true });
  execSync(`git -c core.hooksPath="" init -b main`, { cwd: repoDir, stdio: "ignore" });
  execSync(`git -c core.hooksPath="" config user.name "Test Runner"`, {
    cwd: repoDir,
    stdio: "ignore",
  });
  execSync(`git -c core.hooksPath="" config user.email "test@secureflow.local"`, {
    cwd: repoDir,
    stdio: "ignore",
  });
  execSync(`git -c core.hooksPath="" config commit.gpgsign false`, {
    cwd: repoDir,
    stdio: "ignore",
  });
}

describe("CLI init command end-to-end tests", () => {
  let tempBaseDir: string;

  beforeAll(() => {
    // Ensure CLI binary is compiled
    if (!fs.existsSync(BIN_PATH)) {
      execSync("npm run build", { cwd: CLI_DIR, stdio: "ignore" });
    }
  }, 60000);

  afterEach(() => {
    if (tempBaseDir && fs.existsSync(tempBaseDir)) {
      try {
        fs.rmSync(tempBaseDir, { recursive: true, force: true });
      } catch {
        // Ignored on Windows file locks
      }
    }
  });

  it("creates a commented .secureflow.json in --yes mode without prompting", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-yes-"));
    const res = runCli(["init", "--yes"], tempBaseDir);

    expect(res.status).toBe(0);
    expect(res.stdout).toContain("Created configuration file at .secureflow.json");

    const configPath = path.join(tempBaseDir, ".secureflow.json");
    expect(fs.existsSync(configPath)).toBe(true);

    const content = fs.readFileSync(configPath, "utf-8");
    expect(content).toContain("// SecureFlow Configuration");
    expect(content).toContain("// Generated by `secureflow init`");
    expect(content).toContain('"paths": [\n');
    expect(content).toContain('"src/**"');
    expect(content).toContain('"severity": "high"');
    expect(content).toContain('"aiRemediation": true');
  });

  it("supports short -y flag for accepting defaults", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-shorty-"));
    const res = runCli(["init", "-y"], tempBaseDir);

    expect(res.status).toBe(0);
    const configPath = path.join(tempBaseDir, ".secureflow.json");
    expect(fs.existsSync(configPath)).toBe(true);
  });

  it("prompts interactively and writes custom configuration values", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-interactive-"));

    // Provide user answers:
    // 1. scan paths: "src/**, app/**"
    // 2. minimum severity: "critical"
    // 3. AI remediation: "n"
    const input = "src/**, app/**\ncritical\nn\n";
    const res = runCli(["init"], tempBaseDir, input);

    expect(res.status).toBe(0);
    expect(res.stdout).toContain("Created configuration file at .secureflow.json");

    const configPath = path.join(tempBaseDir, ".secureflow.json");
    const content = fs.readFileSync(configPath, "utf-8");

    expect(content).toContain('"src/**"');
    expect(content).toContain('"app/**"');
    expect(content).toContain('"severity": "critical"');
    expect(content).toContain('"aiRemediation": false');
  });

  it("prompts interactively and uses defaults when Enter is pressed for all questions", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-empty-answers-"));

    const input = "\n\n\n";
    const res = runCli(["init"], tempBaseDir, input);

    expect(res.status).toBe(0);
    const configPath = path.join(tempBaseDir, ".secureflow.json");
    const content = fs.readFileSync(configPath, "utf-8");

    expect(content).toContain('"src/**"');
    expect(content).toContain('"severity": "high"');
    expect(content).toContain('"aiRemediation": true');
  });

  it("refuses to overwrite an existing configuration file without --force", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-refuse-"));
    const configPath = path.join(tempBaseDir, ".secureflow.json");
    fs.writeFileSync(configPath, '{"custom": "existing-content"}');

    const res = runCli(["init", "--yes"], tempBaseDir);

    expect(res.status).toBe(1);
    expect(res.stderr).toContain(
      "Configuration file already exists at .secureflow.json. Use --force to overwrite.",
    );

    // File content remains unchanged
    expect(fs.readFileSync(configPath, "utf-8")).toBe('{"custom": "existing-content"}');
  });

  it("overwrites existing configuration file when --force is passed", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-force-"));
    const configPath = path.join(tempBaseDir, ".secureflow.json");
    fs.writeFileSync(configPath, '{"custom": "existing-content"}');

    const res = runCli(["init", "--yes", "--force"], tempBaseDir);

    expect(res.status).toBe(0);
    expect(res.stdout).toContain("Overwrote existing configuration file at .secureflow.json");

    const content = fs.readFileSync(configPath, "utf-8");
    expect(content).toContain('"severity": "high"');
    expect(content).not.toContain("existing-content");
  });

  it("running init in an empty project produces a config that scan accepts", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-scan-accepts-"));
    initGitRepo(tempBaseDir);

    // 1. Run init in empty project
    const initRes = runCli(["init", "--yes"], tempBaseDir);
    expect(initRes.status).toBe(0);
    expect(fs.existsSync(path.join(tempBaseDir, ".secureflow.json"))).toBe(true);

    // 2. Run scan in the empty project
    const scanRes = runCli([], tempBaseDir);
    expect(scanRes.status).toBe(0);
    expect(scanRes.stdout).toContain("✅ SecureFlow scan passed (0 staged file(s)).");
  });

  it("scan honors path and severity settings configured via init", () => {
    tempBaseDir = fs.mkdtempSync(path.join(os.tmpdir(), "sf-init-scan-honors-"));
    initGitRepo(tempBaseDir);

    // Init with paths restricted to "src/**"
    const input = "src/**\nhigh\ny\n";
    runCli(["init"], tempBaseDir, input);

    // Create a violation outside src/** (should be ignored by paths filter)
    fs.mkdirSync(path.join(tempBaseDir, "other"), { recursive: true });
    fs.writeFileSync(
      path.join(tempBaseDir, "other/ignored.ts"),
      'console.log("Secret:", process.env.API_KEY);\n',
    );
    execSync(`git -c core.hooksPath="" add other/ignored.ts`, { cwd: tempBaseDir });

    // Scan should pass because other/ignored.ts does not match "src/**"
    const scanRes = runCli([], tempBaseDir);
    expect(scanRes.status).toBe(0);
    expect(scanRes.stdout).toContain("✅ SecureFlow scan passed (0 staged file(s)).");

    // Now add a violation inside src/**
    fs.mkdirSync(path.join(tempBaseDir, "src"), { recursive: true });
    fs.writeFileSync(
      path.join(tempBaseDir, "src/leak.ts"),
      'console.log("Secret:", process.env.API_KEY);\n',
    );
    execSync(`git -c core.hooksPath="" add src/leak.ts`, { cwd: tempBaseDir });

    // Scan should now catch the violation in src/leak.ts and block
    const leakRes = runCli([], tempBaseDir);
    expect(leakRes.status).toBe(1);
    expect(leakRes.stdout + leakRes.stderr).toContain("src/leak.ts");
    expect(leakRes.stdout + leakRes.stderr).toContain("SecureFlow blocked this commit");
  });
});
